export const RECOMMENDED_LANGUAGE_CODES: SupportedLanguageCode[] = ['en', 'hi', 'or', 'hi-Latn'];

export function isRTL(code: SupportedLanguageCode): boolean {
  return LANGUAGES[code]?.dir === 'rtl';
}

export function getLanguage(code: string): LanguageMeta {
  if (code in LANGUAGES) {
    return LANGUAGES[code as SupportedLanguageCode];
  }
  return LANGUAGES.en;
}

export function getFallbackChain(code: SupportedLanguageCode): SupportedLanguageCode[] {
  return LANGUAGES[code]?.fallbackChain || ['en'];
}
